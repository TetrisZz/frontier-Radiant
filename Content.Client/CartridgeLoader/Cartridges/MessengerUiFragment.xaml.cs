public sealed partial class MessengerUiFragment : BoxContainer
{
    private MessengerUiState? _state;
    private int _currentPartnerId;
    private int _expandedFriendId;
    private bool _creatingGroup;
    private string _groupName = string.Empty;
    private string _discoverSearch = string.Empty;
    private bool _choosingProfilePhoto;
    private bool _choosingChatPhoto;
    private int _cameraPhotoCount;
    private List<byte[]> _cameraPhotos = [];
    private readonly HashSet<int> _selectedGroupMembers = new();
    private int _scrollChatFramesRemaining;
    private int _chatPartnerId;
    private int _chatMessageCount = -1;

    public event Action<MessengerUiAction, int, string?, List<int>?>? OnAction;
    // Radiant Sector: keeps photo-library indices separate from text message data.
    public event Action<MessengerUiAction, int, int>? OnPhotoAction;

    public MessengerUiFragment()
    {
        RobustXamlLoader.Load(this);
        Orientation = LayoutOrientation.Vertical;
        HorizontalExpand = true;
        VerticalExpand = true;

        FriendsTabButton.OnPressed += _ => ShowFriends();
        DialogsTabButton.OnPressed += _ => ShowDialogs();
        BackButton.OnPressed += _ => ShowDialogs();
        ContactExchangeButton.OnPressed += _ => OnAction?.Invoke(MessengerUiAction.Refresh, 0, null, null);
        ProfileButton.OnPressed += _ =>
        {
            _creatingGroup = false;
            if (_cameraPhotoCount == 0)
            {
                // Radiant Sector: with an empty gallery, go directly to the camera instead of an empty picker.
                OnAction?.Invoke(MessengerUiAction.CaptureProfilePhoto, 0, null, null);
                return;
            }

            _choosingProfilePhoto = true;
            ShowFriends();
        };
        NotificationsButton.OnPressed += _ => OnAction?.Invoke(MessengerUiAction.ToggleNotifications, 0, null, null);
        DiscoverSearch.OnTextChanged += args => OnDiscoverSearchChanged(args.Text);
        CreateGroupButton.OnPressed += _ =>
        {
            _creatingGroup = true;
            ShowFriends();
            if (_state == null)
            {
                FriendsContainer.RemoveAllChildren();
                FriendsContainer.AddChild(CreateGroupCreator());
            }
            else
            {
                BuildLists();
            }
        };
        SendButton.OnPressed += _ => SendMessage();
        PhotoButton.OnPressed += _ =>
        {
            if (_currentPartnerId == 0)
                return;

            _choosingChatPhoto = true;
            BuildChat();
        };
        MessageInput.OnTextEntered += _ => SendMessage();
        ShowFriends();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_scrollChatFramesRemaining <= 0)
            return;

        MessagesScroll.VScrollTarget = float.MaxValue;
        _scrollChatFramesRemaining--;
    }

    public void UpdateState(MessengerUiState state)
    {
        _state = state;
        _cameraPhotoCount = state.CameraPhotoCount;
        _cameraPhotos = state.CameraPhotos;
        NotificationsButton.Text = Loc.GetString(state.NotificationsEnabled ? "messenger-notifications-on" : "messenger-notifications-off");

        if (!_creatingGroup && ShouldRebuildLists())
            BuildLists();

        if (ChatPage.Visible && _currentPartnerId != 0)
        {
            var messages = GetCurrentChatMessages().ToList();
            if (_currentPartnerId != _chatPartnerId || messages.Count != _chatMessageCount)
            {
                var scrollToBottom = _currentPartnerId != _chatPartnerId || messages.Count > _chatMessageCount;
                _chatPartnerId = _currentPartnerId;
                _chatMessageCount = messages.Count;
                BuildChat(scrollToBottom);
            }
        }
    }

    private bool ShouldRebuildLists() =>
        FriendsView.Visible || (DialogsView.Visible && DialogsListPage.Visible);

    private void ShowFriends()
    {
        _currentPartnerId = 0;
        FriendsView.Visible = true;
        DialogsView.Visible = false;
        FriendsTabButton.Disabled = true;
        DialogsTabButton.Disabled = false;
        ResetScroll(FriendsScroll);
        BuildLists();
    }

    private void ShowDialogs()
    {
        _currentPartnerId = 0;
        FriendsView.Visible = false;
        DialogsView.Visible = true;
        DialogsListPage.Visible = true;
        ChatPage.Visible = false;
        FriendsTabButton.Disabled = false;
        DialogsTabButton.Disabled = true;
        ResetScroll(DialogsScroll);
        BuildLists();
    }

    private void OnDiscoverSearchChanged(string text)
    {
        _discoverSearch = text.Trim();
        BuildDiscoverList();
        ResetScroll(FriendsScroll);
    }

    private void BuildLists()
    {
        if (_state == null)
            return;

        FriendsContainer.RemoveAllChildren();
        DialogsContainer.RemoveAllChildren();
        RequestsContainer.RemoveAllChildren();

        if (_choosingProfilePhoto)
        {
            FriendsContainer.AddChild(CreateProfilePhotoPicker());
            EmptyContactsLabel.Visible = false;
            RequestsSection.Visible = false;
            DiscoverSection.Visible = false;
            return;
        }

        DiscoverSection.Visible = true;
        if (_creatingGroup)
            FriendsContainer.AddChild(CreateGroupCreator());

        foreach (var contact in _state.Contacts)
        {
            FriendsContainer.AddChild(CreateFriendCard(contact));
            DialogsContainer.AddChild(CreateDialogCard(contact));
        }

        foreach (var group in _state.Groups)
            DialogsContainer.AddChild(CreateGroupCard(group));

        foreach (var request in _state.IncomingRequests)
            RequestsContainer.AddChild(CreateRequestCard(request));

        BuildDiscoverList();

        EmptyContactsLabel.Visible = _state.Contacts.Count == 0 && !_creatingGroup;
        EmptyDialogsLabel.Visible = _state.Contacts.Count == 0 && _state.Groups.Count == 0;
        RequestsSection.Visible = _state.IncomingRequests.Count > 0;
    }

    private void BuildDiscoverList()
    {
        DiscoverContainer.RemoveAllChildren();

        if (_state == null)
            return;

        var users = string.IsNullOrEmpty(_discoverSearch)
            ? _state.AvailableUsers
            : _state.AvailableUsers
                .Where(user => user.Name.Contains(_discoverSearch, StringComparison.OrdinalIgnoreCase))
                .ToList();

        foreach (var user in users)
            DiscoverContainer.AddChild(CreateDiscoverCard(user));

        EmptyDiscoverLabel.Visible = users.Count == 0;
    }

    private Control CreateFriendCard(MessengerContactEntry friend)
    {
        var card = CreateCard("#202C39", "#31465A");
        var contents = new BoxContainer { Orientation = LayoutOrientation.Vertical, HorizontalExpand = true };
        var select = new Button { HorizontalExpand = true };
        var row = new BoxContainer { Orientation = LayoutOrientation.Horizontal, HorizontalExpand = true, Margin = new Thickness(6, 5) };
        row.AddChild(CreateAvatar(friend.Name, "#527DA3", friend.ProfilePhoto));
        row.AddChild(new Label { Text = friend.Name, HorizontalExpand = true, VerticalAlignment = VAlignment.Center, Margin = new Thickness(8, 0), ClipText = true });
        select.AddChild(row);
        select.OnPressed += _ =>
        {
            _expandedFriendId = _expandedFriendId == friend.Id ? 0 : friend.Id;
            BuildLists();
        };
        contents.AddChild(select);

        if (_expandedFriendId == friend.Id)
        {
            var actions = new BoxContainer { Orientation = LayoutOrientation.Horizontal, HorizontalAlignment = HAlignment.Right, Margin = new Thickness(6, 0, 6, 5) };
            var message = new Button { Text = Loc.GetString("messenger-open-chat"), MinWidth = 100 };
            message.OnPressed += _ => OpenChat(friend.Id, friend.Name);
            var remove = new Button { Text = Loc.GetString("messenger-remove-friend"), MinWidth = 80, Margin = new Thickness(4, 0, 0, 0) };
            remove.OnPressed += _ => OnAction?.Invoke(MessengerUiAction.RemoveContact, friend.Id, null, null);
            actions.AddChild(message);
            actions.AddChild(remove);
            contents.AddChild(actions);
        }

        card.AddChild(contents);
        return card;
    }

    private Control CreateDialogCard(MessengerContactEntry contact)
    {
        var card = CreateCard("#202C39", "#31465A");
        var button = new Button { HorizontalExpand = true };
        var row = new BoxContainer { Orientation = LayoutOrientation.Horizontal, HorizontalExpand = true, Margin = new Thickness(6, 5) };
        row.AddChild(CreateAvatar(contact.Name, "#527DA3", contact.ProfilePhoto));
        var details = new BoxContainer { Orientation = LayoutOrientation.Vertical, HorizontalExpand = true, Margin = new Thickness(8, 0) };
        details.AddChild(new Label { Text = contact.Name, HorizontalExpand = true, ClipText = true });
        var last = _state?.Messages
            .Where(m => m.GroupId == 0 && (m.SenderId == contact.Id || m.ReceiverId == contact.Id))
            .OrderByDescending(m => m.Timestamp)
            .FirstOrDefault();
        details.AddChild(new Label { Text = last?.Content ?? Loc.GetString("messenger-no-messages"), FontColorOverride = Color.FromHex("#9EB1C0"), HorizontalExpand = true, ClipText = true });
        row.AddChild(details);
        if (contact.UnreadCount > 0)
            row.AddChild(CreateUnreadBadge(contact.UnreadCount));
        button.AddChild(row);
        button.OnPressed += _ => OpenChat(contact.Id, contact.Name);
        card.AddChild(button);
        return card;
    }

