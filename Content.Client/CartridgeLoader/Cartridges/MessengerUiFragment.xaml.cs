    private static void ResetScroll(ScrollContainer scroll) =>
        scroll.SetScrollValue(Vector2.Zero);

    private static PanelContainer CreateCard(string color, string borderColor) => new()
    {
        PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex(color), BorderColor = Color.FromHex(borderColor), BorderThickness = new Thickness(1) },
        Margin = new Thickness(8, 0, 8, 4),
        HorizontalExpand = true,
    };

    private static Texture LoadAvatarTexture(byte[] profilePhoto)
    {
        using var stream = new MemoryStream(profilePhoto);
        var texture = Texture.LoadFromPNGStream(stream);

        // Radiant Sector: photo frames are wide scene captures; a centered crop keeps avatar thumbnails legible.
        var cropSize = (int) (Math.Min(texture.Width, texture.Height) * 0.6f);
        if (cropSize < 2)
            return texture;

        var left = (texture.Width - cropSize) / 2;
        var top = (texture.Height - cropSize) / 2;
        return new AtlasTexture(texture, UIBox2.FromDimensions(new Vector2(left, top), new Vector2(cropSize, cropSize)));
    }

    private static Control CreateAvatar(string name, string color, byte[]? profilePhoto = null)
    {
        if (profilePhoto != null)
        {
            try
            {
                // Radiant Sector: a photo thumbnail owns its full fixed area, avoiding a second frame that can shift in list rows.
                return new TextureRect
                {
                    Texture = LoadAvatarTexture(profilePhoto),
                    Stretch = TextureRect.StretchMode.Scale,
                    CanShrink = true,
                    MinSize = new Vector2(32, 32),
                    MaxSize = new Vector2(32, 32),
                    HorizontalAlignment = HAlignment.Center,
                    VerticalAlignment = VAlignment.Center,
                    RectClipContent = true,
                };
            }
            catch
            {
                // Radiant Sector: fall back to the initial when a stored profile image is invalid.
            }
        }

        var avatar = new PanelContainer
        {
            PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex(color), BorderColor = Color.FromHex("#8BB6D8"), BorderThickness = new Thickness(1) },
            MinSize = new Vector2(32, 32),
            MaxSize = new Vector2(32, 32),
            VerticalAlignment = VAlignment.Center,
        };
        avatar.AddChild(new Label { Text = string.IsNullOrWhiteSpace(name) ? "?" : name[..1].ToUpperInvariant(), Align = Label.AlignMode.Center, VerticalAlignment = VAlignment.Center });
        return avatar;
    }

    private static PanelContainer CreateUnreadBadge(int count)
    {
        var badge = new PanelContainer { PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#4FA3E3"), BorderColor = Color.FromHex("#8BC8F5"), BorderThickness = new Thickness(1) }, MinSize = new Vector2(24, 20), VerticalAlignment = VAlignment.Center };
        badge.AddChild(new Label { Text = count.ToString(), Align = Label.AlignMode.Center, VerticalAlignment = VAlignment.Center });
        return badge;
    }
