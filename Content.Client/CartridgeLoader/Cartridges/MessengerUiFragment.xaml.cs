    private void OpenChat(int partnerId, string name)
    {
        _creatingGroup = false;
        _choosingChatPhoto = false;
        _currentPartnerId = partnerId;
        PartnerLabel.Text = name;
        // Radiant Sector: direct-dialog headers show the contact's selected profile photo.
        var profilePhoto = partnerId > 0
            ? _state?.Contacts.FirstOrDefault(contact => contact.Id == partnerId)?.ProfilePhoto
            : null;
        SetPartnerAvatar(name, profilePhoto);
        PartnerTypeLabel.Text = Loc.GetString(partnerId < 0 ? "messenger-group" : "messenger-contact");
        FriendsView.Visible = false;
        DialogsView.Visible = true;
        DialogsListPage.Visible = false;
        ChatPage.Visible = true;
        FriendsTabButton.Disabled = false;
        DialogsTabButton.Disabled = true;
        OnAction?.Invoke(MessengerUiAction.ReadChat, partnerId, null, null);
        _chatPartnerId = 0;
        _chatMessageCount = -1;
        BuildChat(scrollToBottom: true);
    }

    private void SetPartnerAvatar(string name, byte[]? profilePhoto)
    {
        PartnerInitial.Text = string.IsNullOrWhiteSpace(name) ? "?" : name[..1].ToUpperInvariant();
        PartnerInitial.Visible = true;
        PartnerPhoto.Visible = false;
        PartnerPhoto.Texture = null;

        if (profilePhoto == null || profilePhoto.Length == 0)
            return;

        try
        {
            PartnerPhoto.Texture = LoadAvatarTexture(profilePhoto);
            PartnerPhoto.Visible = true;
            PartnerInitial.Visible = false;
        }
        catch
        {
            // Radiant Sector: invalid or old avatar data falls back to the contact initial.
        }
    }

    private IEnumerable<MessengerMessageEntry> GetCurrentChatMessages()
    {
        if (_state == null || _currentPartnerId == 0)
            return [];

        return _currentPartnerId < 0
            ? _state.Messages.Where(message => message.GroupId == -_currentPartnerId)
            : _state.Messages.Where(message =>
                message.GroupId == 0 &&
                (message.SenderId == _currentPartnerId || message.ReceiverId == _currentPartnerId));
    }

    private void BuildChat(bool scrollToBottom = false)
    {
        if (_state == null || _currentPartnerId == 0)
            return;

        var scrollPosition = MessagesScroll.GetScrollValue();
        MessagesContainer.RemoveAllChildren();
        if (_choosingChatPhoto)
        {
            MessagesContainer.AddChild(CreateChatPhotoPicker());
            return;
        }
        var messages = GetCurrentChatMessages();

        var isGroupChat = _currentPartnerId < 0;
        foreach (var message in messages.OrderBy(message => message.Timestamp))
        {
            var isOwnMessage = message.SenderId == _state.OwnerId;
            var incoming = isGroupChat ? !isOwnMessage : message.SenderId == _currentPartnerId;
            var bubble = CreateCard(incoming ? "#263B50" : "#2B6D67", incoming ? "#466781" : "#4D9C92");
            bubble.HorizontalAlignment = incoming ? HAlignment.Left : HAlignment.Right;
            bubble.HorizontalExpand = false;
            var time = message.Timestamp.ToString(@"hh\:mm");
            var showSender = (isGroupChat || incoming) && !isOwnMessage;
            var contents = new BoxContainer
            {
                Orientation = LayoutOrientation.Vertical,
                HorizontalExpand = true,
                Margin = new Thickness(7, 5),
            };

            if (showSender)
                contents.AddChild(new Label { Text = message.SenderName });

            if (message.ImageData != null)
            {
                try
                {
                    using var stream = new MemoryStream(message.ImageData);
                    contents.AddChild(new TextureRect
                    {
                        Texture = Texture.LoadFromPNGStream(stream),
                        Stretch = TextureRect.StretchMode.KeepAspectCentered,
                        MinSize = new Vector2(180, 140),
                    });
                }
                catch
                {
                    // Radiant Sector: corrupt network image data must not break the chat window.
                }
            }

            if (!string.IsNullOrEmpty(message.Content))
            {
                // Radiant Sector: RichTextLabel wraps plain text to the available chat width instead of clipping it.
                var text = new RichTextLabel { HorizontalExpand = true };
                text.SetMessage(message.Content);
                contents.AddChild(text);
            }
            contents.AddChild(new Label { Text = time });
            bubble.AddChild(contents);
            MessagesContainer.AddChild(bubble);
        }

        if (scrollToBottom)
            _scrollChatFramesRemaining = 3;
        else
            MessagesScroll.SetScrollValue(scrollPosition);
    }

    private void SendMessage()
    {
        var text = MessageInput.Text.Trim();
        if (string.IsNullOrEmpty(text) || _currentPartnerId == 0)
            return;

        OnAction?.Invoke(MessengerUiAction.SendMessage, _currentPartnerId, text, null);
        MessageInput.Clear();
    }

    private Control CreateChatPhotoPicker()
    {
        var card = CreateCard("#27394A", "#5B8CB4");
        var box = new BoxContainer { Orientation = LayoutOrientation.Vertical, HorizontalExpand = true, Margin = new Thickness(6) };
        box.AddChild(new Label { Text = Loc.GetString("messenger-send-photo") });

