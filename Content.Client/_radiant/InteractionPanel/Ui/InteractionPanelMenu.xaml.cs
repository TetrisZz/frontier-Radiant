        private EntityUid? GetInteractionTarget(EntityUid user)
        {
            if (SoloModeCheckBox.Pressed)
                return null;

            return FindTarget(user);
        }

        private EntityUid? FindTarget(EntityUid user)
        {
            if (!_entManager.TryGetComponent<TransformComponent>(user, out var sourceTransform))
                return null;

            EntityUid? bestTarget = null;
            var bestDistance = float.MaxValue;

            void Consider(EntityUid candidate)
            {
                if (candidate == user || !IsValidInteractionTarget(candidate))
                    return;

                if (!_interaction.InRangeUnobstructed(user, candidate, range: TargetSearchRange, popup: false))
                    return;

                var distance = (_transform.GetWorldPosition(user) - _transform.GetWorldPosition(candidate)).LengthSquared();
                if (distance >= bestDistance)
                    return;

                bestDistance = distance;
                bestTarget = candidate;
            }

            foreach (var entity in _lookup.GetEntitiesInRange<HumanoidAppearanceComponent>(sourceTransform.Coordinates, TargetSearchRange))
                Consider(entity.Owner);

            foreach (var strapEntity in _lookup.GetEntitiesInRange<StrapComponent>(sourceTransform.Coordinates, TargetSearchRange))
            {
                if (!_entManager.TryGetComponent<StrapComponent>(strapEntity.Owner, out var strapComponent))
                    continue;

                foreach (var buckledEntity in strapComponent.BuckledEntities)
                    Consider(buckledEntity);
            }

            return bestTarget;
        }

        private bool IsValidInteractionTarget(EntityUid entity)
        {
            if (!_entManager.HasComponent<HumanoidAppearanceComponent>(entity) || IsErpDenied(entity))
                return false;

            if (!IsPlayerTarget(entity))
                return false;

            if (_entManager.TryGetComponent<MobThresholdsComponent>(entity, out var thresholds) &&
                thresholds.CurrentThresholdState != MobState.Alive &&
                thresholds.CurrentThresholdState != MobState.Invalid)
                return false;

            return true;
        }

        private bool IsPlayerTarget(EntityUid entity)
        {
            foreach (var session in _playerManager.Sessions)
            {
                if (session.AttachedEntity == entity)
                    return true;
            }

            return _entManager.TryGetComponent<MindContainerComponent>(entity, out var mindContainer)
                   && mindContainer.HasMind
                   && !_entManager.HasComponent<ActiveNPCComponent>(entity);
        }

        private bool IsErpDenied(EntityUid uid)
        {
            return _entManager.TryGetComponent<DetailExaminableComponent>(uid, out var detail) &&
                   detail.ERPStatus == EnumERPStatus.NO;
        }
