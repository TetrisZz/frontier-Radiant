        private void UpdateGender(EntityUid entity, HumanoidAppearanceComponent? appearanceComponent, Label genderLabel)
        {
            genderLabel.Orphan();

            if (appearanceComponent == null)
            {
                genderLabel.Text = Loc.GetString("unknown-nearestplayer");
                TargetModel.AddChild(genderLabel);
                return;
            }

            var targetGenderIcon = CreateGenderIconButton(appearanceComponent.Sex);
            if (targetGenderIcon != null)
            {
                targetGenderIcon.Orphan();
                TargetNameRow.AddChild(targetGenderIcon);
            }
            var dionaSpecies = new ProtoId<SpeciesPrototype>("Diona");
            var arachnidSpecies = new ProtoId<SpeciesPrototype>("Arachnid");
            var voxSpecies = new ProtoId<SpeciesPrototype>("Vox");

            genderLabel.Text = TryBuildAdultAnatomyText(entity, false, out var anatomyText)
                ? anatomyText
                : appearanceComponent.Species switch
            {
                var species when species == dionaSpecies => string.Join("\n", new[] { Loc.GetString("diona-leaves"), Loc.GetString("diona-branches") }),
                var species when species == arachnidSpecies => Loc.GetString("arachnid-nearestplayer"),
                var species when species == voxSpecies => Loc.GetString("vox-nearestplayer"),
                _ => appearanceComponent.Sex switch
                {
                    Sex.Male => string.Join("\n", new[] { Loc.GetString("male-anal"), Loc.GetString("male-dick") }),
                    Sex.Female => string.Join("\n", new[] { Loc.GetString("female-anal"), Loc.GetString("female-vagine"), Loc.GetString("female-breasts") }),
                    Sex.Unsexed => Loc.GetString("unsexed-nearestplayer"),
                    _ => Loc.GetString("unknown-nearestplayer")
                }
            };

            genderLabel.Orphan();
            TargetModel.AddChild(genderLabel);
        }

        public void UpdateUser(EntityUid user)
        {
            _userSpriteView.SetEntity(user);

            var dionaSpecies = new ProtoId<SpeciesPrototype>("Diona");
            var arachnidSpecies = new ProtoId<SpeciesPrototype>("Arachnid");
            var voxSpecies = new ProtoId<SpeciesPrototype>("Vox");
            var appearanceComponent = _entManager.GetComponentOrNull<HumanoidAppearanceComponent>(user);

            // Radiant sector: refresh this text for every anatomy state, not only
            // when HumanoidAppearance is missing.
            _userGenderLabel.Text = TryBuildAdultAnatomyText(user, true, out var anatomyText)
                ? anatomyText
                : appearanceComponent?.Species switch
            {
                var species when species == dionaSpecies => string.Join("\n", new[] { Loc.GetString("diona-leaves-player"), Loc.GetString("diona-branches-player") }),
                var species when species == arachnidSpecies => Loc.GetString("arachnid-player"),
                var species when species == voxSpecies => Loc.GetString("vox-player"),
                _ => appearanceComponent?.Sex switch
                {
                    Sex.Male => string.Join("\n", new[] { Loc.GetString("male-anal-player"), Loc.GetString("male-dick-player") }),
                    Sex.Female => string.Join("\n", new[] { Loc.GetString("female-anal-player"), Loc.GetString("female-vagine-player"), Loc.GetString("female-breasts-player") }),
                    Sex.Unsexed => Loc.GetString("unsexed-player"),
                    _ => Loc.GetString("unknown-player")
                }
            };

            _userGenderLabel.Orphan();
            UserModel.AddChild(_userGenderLabel);
        }

        // Radiant sector: the panel follows surgically installed anatomy instead of immutable profile sex.
        private bool TryBuildAdultAnatomyText(EntityUid entity, bool self, out string text)
        {
            text = string.Empty;
            if (!_entManager.TryGetComponent<AdultAnatomyComponent>(entity, out var anatomy) || !anatomy.AnatomyInitialized)
                return false;

            var suffix = self ? "-player" : string.Empty;
            var parts = new List<string> { Loc.GetString($"adult-anatomy-anal{suffix}") };
            if (anatomy.HasPenis)
            {
                parts.Add(Loc.GetString($"adult-anatomy-penis{suffix}"));
                if (!anatomy.PenisNervesIntact)
                    parts.Add(Loc.GetString($"adult-anatomy-penis-denervated{suffix}"));
            }
            if (anatomy.HasVagina)
