        protected override void FrameUpdate(FrameEventArgs args)
        {
            base.FrameUpdate(args);
            if (_restoreScrollFrames > 0 && --_restoreScrollFrames == 0)
                Scroll.SetScrollValue(new Vector2(0, _preferences.Scroll));

            var session = _playerManager.LocalSession;
            if (session?.AttachedEntity is { } user && IsErpDenied(user))
            {
                Close();
                return;
            }

            UpdateArousalBar();

            _updateDif += args.DeltaSeconds;
            if (_updateDif < TargetUpdateInterval)
                return;

            _updateDif -= TargetUpdateInterval;

            // Update panel
            InitializeNamesContainer();
            PopulateInteractions(false);
            UpdateTarget();
        }

        protected override void Dispose(bool disposing)
        {
            if (disposing)
                _playerManager.PlayerStatusChanged -= OnUserStatusChanged;
            base.Dispose(disposing);
        }

