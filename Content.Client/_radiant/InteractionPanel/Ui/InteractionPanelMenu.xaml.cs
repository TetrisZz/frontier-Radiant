            HeadContainer.RemoveAllChildren();
            ChestContainer.RemoveAllChildren();
            GroinContainer.RemoveAllChildren();
            TailContainer.RemoveAllChildren();
            BodyContainer.RemoveAllChildren();

            foreach (var buttonContainer in _allButtons)
            {
                var button = buttonContainer.Children.OfType<Button>().FirstOrDefault();
                if (button == null || string.IsNullOrEmpty(button.Name)) continue;

                bool isVisible = !FavoritesOnlyButton.Pressed && MatchesFilters(button, searchText);

                if (isVisible)
                {
                    var prototype = _prototypeManager.Index<InteractionPrototype>(button.Name);
                    if (prototype == null) continue;

                    GetContainerByCategory(prototype).AddChild(buttonContainer);
                }
            }

            foreach (var buttonContainer in _importedButtons)
            {
                var button = buttonContainer.Children.OfType<Button>().FirstOrDefault();
                if (button == null || string.IsNullOrEmpty(button.Name)) continue;

                bool isVisible = !FavoritesOnlyButton.Pressed && MatchesFilters(button, searchText);

                if (isVisible)
                {
                    SpecialContainer.AddChild(buttonContainer);
                }
            }

            foreach (var buttonContainer in _favoriteButtons)
            {
                var button = buttonContainer.Children.OfType<Button>().FirstOrDefault();
                if (button == null || string.IsNullOrEmpty(button.Name)) continue;

                bool isVisible = MatchesFilters(button, searchText);

                if (isVisible)
                {
                    FavouritesContainer.AddChild(buttonContainer);
                }
            }
            var count = _allButtons.Concat(_importedButtons).Concat(_favoriteButtons)
                .Where(row => row.Parent != null)
                .Select(row => row.Children.OfType<Button>().First().Name)
                .Distinct().Count();
            SearchResults.Text = Loc.GetString("interaction-panel-search-results", ("count", count));
            EmptyResults.Visible = count == 0;
            EmptyResults.Text = Loc.GetString(searchText.Length == 0
                ? "interaction-panel-empty-available"
                : "interaction-panel-search-empty");
            foreach (var group in InteractionContainer.Children.OfType<Collapsible>())
            {
                var content = group.Children.OfType<CollapsibleBody>().First()
                    .Children.OfType<BoxContainer>().First();
                group.Visible = content.ChildCount > 0;
                var heading = group.Children.OfType<CollapsibleHeading>().First();
                heading.Label.Text = $"{_headingTitles[heading]} ({content.ChildCount})";
            }
            _preferences.Scroll = previousScroll;
            _restoreScrollFrames = 2;
        }

