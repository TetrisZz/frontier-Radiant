        private static IEnumerable<InteractionPrototype> SortInteractions(IEnumerable<InteractionPrototype> prototypes)
        {
            var list = prototypes.ToList();
            list.Sort((a, b) =>
            {
                var solo = a.Solo.CompareTo(b.Solo);
                if (solo != 0)
                    return solo;

                var erp = a.ERP.CompareTo(b.ERP);
                if (erp != 0)
                    return erp;

                var name = string.Compare(
                    Loc.GetString(a.Name),
                    Loc.GetString(b.Name),
                    StringComparison.CurrentCultureIgnoreCase);
                if (name != 0)
                    return name;

                return string.Compare(a.ID, b.ID, StringComparison.Ordinal);
            });

            return list;
        }

        private BoxContainer GetContainerByCategory(InteractionPrototype prototype)
        {
            return prototype.Category.ToLowerInvariant() switch
            {
                "lips" or "lip" or "губы" => LipsContainer,
                "head" or "голова" => HeadContainer,
                "chest" or "breasts" or "грудь" => ChestContainer,
                "groin" or "genitals" or "промежность" => GroinContainer,
                "tail" or "хвост" => TailContainer,
                "body" or "тело" => BodyContainer,
                _ => BodyContainer
            };
        }

