        private bool ApplyAvailability(Button button, InteractionPrototype prototype, EntityUid user, EntityUid? target)
        {
            string? reason = null;
            if (!prototype.Solo && target == null)
                reason = "interaction-panel-unavailable-no-target";
            else if (target is { } partner)
            {
                if ((_transform.GetWorldPosition(user) - _transform.GetWorldPosition(partner)).LengthSquared() > TargetSearchRange * TargetSearchRange)
                    reason = "interaction-panel-unavailable-distance";
                else if (!_interaction.InRangeUnobstructed(user, partner, range: TargetSearchRange,
                             collisionMask: Content.Shared.Physics.CollisionGroup.Impassable, popup: false))
                    reason = "interaction-panel-unavailable-obstacle";
            }
            if (reason == null && _entManager.System<InteractionClothingSystem>().IsBlocked(user, target, prototype, out var targetBlocked))
                reason = targetBlocked ? "interaction-panel-unavailable-target-clothing" : "interaction-panel-unavailable-user-clothing";
            var changed = button.Disabled != (reason != null);
            button.Disabled = reason != null;
            button.ToolTip = reason == null ? button.Text : $"{button.Text}\n{Loc.GetString(reason)}";
            return changed;
        }

        private bool IsInteractionAllowed(InteractionPrototype prototype, HumanoidAppearanceComponent userAppearance, EntityUid target)
        {
            if (!_entManager.TryGetComponent<HumanoidAppearanceComponent>(target, out var targetAppearance))
                return false;

            bool isSpeciesAllowed = prototype.AllowedSpecies?.Contains("all") == true || prototype.AllowedSpecies?.Contains(userAppearance.Species) == true;
            bool isSpeciesBlacklisted = prototype.BlackListSpecies?.Contains(userAppearance.Species) == true || prototype.BlackListSpecies?.Contains(targetAppearance.Species) == true;
            bool isGenderAllowed = IsUserAnatomyAllowed(prototype, userAppearance);
            bool isNearestSpeciesAllowed = prototype.NearestAllowedSpecies?.Contains("all") == true || prototype.NearestAllowedSpecies?.Contains(targetAppearance.Species) == true;
            bool isNearestGenderAllowed = IsTargetAnatomyAllowed(prototype, targetAppearance, target);
            bool isTargetEntityAllowed = prototype.TargetEntityId == null || prototype.TargetEntityId.Contains(target.ToString());


            return isSpeciesAllowed && !isSpeciesBlacklisted && isGenderAllowed && isNearestSpeciesAllowed && isNearestGenderAllowed && isTargetEntityAllowed;
        }

        private bool IsInteractionVisible(InteractionPrototype prototype, HumanoidAppearanceComponent userAppearance, EntityUid? target)
        {
            if (SoloModeCheckBox.Pressed)
                return prototype.Solo && IsSoloInteractionAllowed(prototype, userAppearance);

            if (target == null)
                return !prototype.Solo && IsSoloInteractionAllowed(prototype, userAppearance);

            return !prototype.Solo && IsInteractionAllowed(prototype, userAppearance, target.Value);
        }

        private bool IsSoloInteractionAllowed(InteractionPrototype prototype, HumanoidAppearanceComponent userAppearance)
        {
            var isSpeciesAllowed = prototype.AllowedSpecies?.Contains("all") == true || prototype.AllowedSpecies?.Contains(userAppearance.Species) == true;
            var isSpeciesBlacklisted = prototype.BlackListSpecies?.Contains(userAppearance.Species) == true;
            var isGenderAllowed = IsUserAnatomyAllowed(prototype, userAppearance);

            return isSpeciesAllowed && !isSpeciesBlacklisted && isGenderAllowed;
        }

        private bool IsUserAnatomyAllowed(InteractionPrototype prototype, HumanoidAppearanceComponent appearance)
        {
            if (_playerManager.LocalSession?.AttachedEntity is not { } user
                || !_entManager.System<InteractionBodyFeatureSystem>()
                    .HasRequiredFeatures(user, prototype.UserRequiredBodyFeatures))
                return false;
            var genders = prototype.AllowedGenders;
            if (genders?.Contains("all") == true)
                return true;
            var uid = _playerManager.LocalSession?.AttachedEntity;
            if (uid == null || !_entManager.TryGetComponent<AdultAnatomyComponent>(uid.Value, out var anatomy))
                return genders?.Contains(appearance.Sex.ToString()) == true;
            if (genders?.Contains("Male") == true && anatomy.HasPenis)
                return true;
            if (genders?.Contains("Female") == true)
                return prototype.Category.Equals("chest", StringComparison.OrdinalIgnoreCase)
                    ? anatomy.HasBreasts
                    : anatomy.HasVagina;
            return false;
        }

        private bool IsTargetAnatomyAllowed(InteractionPrototype prototype, HumanoidAppearanceComponent appearance, EntityUid uid)
        {
            if (!_entManager.System<InteractionBodyFeatureSystem>()
                    .HasRequiredFeatures(uid, prototype.TargetRequiredBodyFeatures))
                return false;
            var genders = prototype.NearestAllowedGenders;
            if (genders?.Contains("all") == true)
                return true;
            if (!_entManager.TryGetComponent<AdultAnatomyComponent>(uid, out var anatomy))
                return genders?.Contains(appearance.Sex.ToString()) == true;
            if (genders?.Contains("Male") == true && anatomy.HasPenis)
                return true;
            if (genders?.Contains("Female") == true)
                return prototype.Category.Equals("chest", StringComparison.OrdinalIgnoreCase)
                    ? anatomy.HasBreasts
                    : anatomy.HasVagina;
            return false;
        }

        private void OnInteractionPressed(string interactionId)
        {
            var session = _playerManager.LocalSession;
            if (session?.AttachedEntity == null) return;

            var user = session.AttachedEntity.Value;
            if (!_entManager.TryGetNetEntity(user, out var userEntity)) return;

            var target = GetInteractionTarget(user);
            if (target == null &&
                (!_prototypeManager.TryIndex<InteractionPrototype>(interactionId, out var indexed) || !indexed.Solo))
            {
                return;
            }

            var hideFromOthers = HideFromOthersCheckBox.Pressed;
            var hint = GetLocalArousalHint(interactionId, null);
            NetEntity? targetNetEntity = null;
            if (target != null)
                targetNetEntity = _entManager.GetNetEntity(target.Value);

            _entityNetworkManager.SendSystemNetworkMessage(new InteractionPressedEvent(userEntity.Value, interactionId, targetNetEntity, null, hideFromOthers, hint));
        }

        private void OnInteractionPressed(string interactionId, InteractionPrototype prototype)
        {
            var session = _playerManager.LocalSession;
            if (session?.AttachedEntity == null) return;

            var user = session.AttachedEntity.Value;
            if (!_entManager.TryGetNetEntity(user, out var userEntity)) return;

            var target = GetInteractionTarget(user);
            if (target == null && !prototype.Solo)
                return;

            var hideFromOthers = HideFromOthersCheckBox.Pressed;
            var hint = GetLocalArousalHint(interactionId, prototype);
            NetEntity? targetNetEntity = null;
            if (target != null)
                targetNetEntity = _entManager.GetNetEntity(target.Value);

            _entityNetworkManager.SendSystemNetworkMessage(new InteractionPressedEvent(userEntity.Value, interactionId, targetNetEntity, prototype, hideFromOthers, hint));
        }

        private int GetLocalArousalHint(string interactionId, InteractionPrototype? imported)
        {
            if (_prototypeManager.TryIndex<InteractionPrototype>(interactionId, out var indexed))
                return indexed.EffectiveArousal;
            return imported?.EffectiveArousal ?? 0;
        }

        private void OnEditorPressed(InteractionPrototype prototype)
        {
            UserInterfaceManager.GetUIController<InteractionEditorUIController>().ToggleWindow(prototype);
        }
