using Content.Client._Goobstation.Languages;
using System.Linq;
using Content.Client.Corvax.TTS;
using Content.Shared._Goobstation.Languages;
using Content.Shared.Corvax.TTS;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.GameObjects;
using Robust.Shared.IoC;
using Robust.Shared.Prototypes;

namespace Content.Client._Goobstation.Languages.UI;

/// <summary>
/// Radiant Sector: compact in-game language selector inspired by the language menus in upstream builds.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class LanguageMenuWindow : DefaultWindow
{
    private readonly LanguageMenuSystem _languageMenu;
    private string _nativeLanguage = string.Empty;
    private LanguageInfoWindow? _infoWindow;
    private readonly List<TTSVoicePrototype> _voices = new();
    private string? _currentVoice;
    private int _selectedVoice = -1;

    public LanguageMenuWindow()
    {
        RobustXamlLoader.Load(this);
        _languageMenu = IoCManager.Resolve<IEntitySystemManager>().GetEntitySystem<LanguageMenuSystem>();

        CommonButton.OnPressed += _ => _languageMenu.SelectLanguage(false);
        NativeButton.OnPressed += _ => _languageMenu.SelectLanguage(true);
        // Radiant Sector: show help for the language beside the pressed question mark.
        CommonInfoButton.OnPressed += _ => OpenLanguageInfo(false);
        NativeInfoButton.OnPressed += _ => OpenLanguageInfo(true);
        VoiceButton.OnItemSelected += args =>
        {
            _selectedVoice = args.Id;
            VoiceButton.SelectId(args.Id);
            UpdateVoiceButtons();
        };
        VoiceApplyButton.OnPressed += _ =>
        {
            if (_selectedVoice >= 0 && _selectedVoice < _voices.Count)
                _languageMenu.SelectVoice(_voices[_selectedVoice].ID);
        };
        VoicePreviewButton.OnPressed += _ =>
        {
            if (_selectedVoice >= 0 && _selectedVoice < _voices.Count)
                IoCManager.Resolve<IEntityManager>().System<TTSSystem>()
                    .RequestPreviewTTS(_voices[_selectedVoice].ID, robotic: true);
        };
    }

    public void UpdateState(LanguageMenuStateEvent state)
    {
        var nativeLanguage = state.NativeLanguage;
        var nativeSelected = state.NativeSelected;
        var canUseNative = state.CanUseNative;
        var canUseGalactic = state.CanUseGalactic;
        _nativeLanguage = nativeLanguage;
        CurrentLanguageLabel.Text = nativeSelected || !canUseGalactic
            ? $"Сейчас выбран: {nativeLanguage}"
            : "Сейчас выбран: Общегалактический";

        CommonButton.Text = canUseGalactic
            ? (nativeSelected ? "Выбрать общегалактический" : "Общегалактический ✓")
            : "Общегалактический недоступен";
        CommonButton.Disabled = !canUseGalactic || !nativeSelected;

        NativeButton.Text = canUseNative
            ? (nativeSelected ? $"{nativeLanguage} ✓" : $"Выбрать: {nativeLanguage}")
            : $"{nativeLanguage} недоступен";
        NativeButton.Disabled = !canUseNative || nativeSelected;
        CommonInfoButton.Visible = canUseGalactic;
        NativeInfoButton.Visible = canUseNative;

        _infoWindow?.UpdateLanguage(nativeLanguage, _infoWindow.ShowingNative);
        VoiceSection.Visible = state.CanSelectVoice;
        if (!state.CanSelectVoice)
            return;

        _currentVoice = state.VoiceId;
        _voices.Clear();
        _voices.AddRange(IoCManager.Resolve<IPrototypeManager>().EnumeratePrototypes<TTSVoicePrototype>()
            .Where(voice => voice.RoundStart || voice.ID == _currentVoice)
            .OrderBy(voice => Loc.GetString(voice.Name)));
        VoiceButton.Clear();
        for (var i = 0; i < _voices.Count; i++)
            VoiceButton.AddItem(Loc.GetString(_voices[i].Name), i);
        _selectedVoice = _voices.FindIndex(voice => voice.ID == _currentVoice);
        if (_selectedVoice < 0 && _voices.Count > 0)
            _selectedVoice = 0;
        if (_selectedVoice >= 0)
            VoiceButton.SelectId(_selectedVoice);
        VoiceButton.Disabled = _voices.Count == 0;
        UpdateVoiceButtons();
    }

    private void UpdateVoiceButtons()
    {
        var valid = _selectedVoice >= 0 && _selectedVoice < _voices.Count;
        VoicePreviewButton.Disabled = !valid;
        VoiceApplyButton.Disabled = !valid || _voices[_selectedVoice].ID == _currentVoice;
    }

    private void OpenLanguageInfo(bool native)
    {
        if (native && string.IsNullOrEmpty(_nativeLanguage))
            return;

        if (_infoWindow == null)
        {
            _infoWindow = new LanguageInfoWindow();
            _infoWindow.OnClose += () => _infoWindow = null;
            _infoWindow.OpenCentered();
        }

        _infoWindow.UpdateLanguage(_nativeLanguage, native);
    }
}
