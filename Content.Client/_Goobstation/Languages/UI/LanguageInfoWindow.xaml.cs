using Content.Client.Message;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Goobstation.Languages.UI;

/// <summary>
/// Radiant Sector: explains only Galactic Common and the selected character's native language.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class LanguageInfoWindow : DefaultWindow
{
    public bool ShowingNative { get; private set; }

    public LanguageInfoWindow()
    {
        RobustXamlLoader.Load(this);
    }

    public void UpdateLanguage(string nativeLanguage, bool native)
    {
        ShowingNative = native;

        if (!native)
        {
            Title = "Общегалактический";
            InfoText.SetMarkup("[bold]Общегалактический[/bold]\n[font size=12][color=#F2F6FB]Основной язык межвидового общения. Понимается всеми, кто не отказался от его знания отдельной чертой речи. Используйте его, если хотите, чтобы вас понял весь экипаж.[/color][/font]");
            return;
        }

        var (species, description, color) = nativeLanguage switch
        {
            "Синта'Унати" => ("унатхам", "общеупотребительный язык унатхов. Его основные звуки напоминают змеиное шипение и дребезжание.", "#2ACA2A"),
            "Вокс-пиджин" => ("воксам", "громкий птичий жаргон с гортанными, велярными и взрывными звуками.", "#A489A0"),
            "Корневой язык" => ("дионам", "скрипучая, едва различимая речь. Одна фраза может состоять из сочетания одного–двенадцати отдельных голосов и нот.", "#A64E14"),
            "Бабблилиш" => ("слаймолюдам", "язык слизней: смесь булькающих звуков и хлюпков. Человеку почти невозможно говорить на нём без вспомогательных средств.", "#24D1B9"),
            "Моффик" => ("нианам", "язык нианов-моле-гуманоидов; для чужого слуха его речь почти полностью непонятна.", "#C7DF2E"),
            "Щёлкающий" => ("арахнидам", "сочетание щелчков, шипения и коротких вибрирующих звуков.", "#B0B0B0"),
            "Канилунц" => ("вульпканинам", "язык со звучанием, отдалённо напоминающим финскую, венгерскую, шведскую и немецкую речь.", "#D69B3D"),
            "Сиик'тайр" => ("таяранам", "родной язык таяр с выразительными завываниями и мяуканьем. Без хвоста и усов передавать часть информации значительно сложнее.", "#D6A36E"),
            "Счечи" => ("резоми", "сравнительно простой язык из хрипов, тресков и писков; нетренированному уху он часто кажется какофонией.", "#4DBFD9"),
            "Нехина" => ("ферокси", "родной язык ферокси.", "#5FAEE3"),
            "Сумеречный" => ("шадовкинам", "тихая, приглушённая речь шадовкинов.", "#C29EFF"),
            "Кхаздар" => ("дворфам", "рубленая ремесленная речь дворфов.", "#C78E42"),
            "Кансэй" => ("они", "японско-онийский общий язык, созданный для понятного общения разных народов.", "#D95B67"),
            "Аэрийский" => ("гарпиям", "певучая речь гарпий с подражанием интонациям и звукам.", "#8ED5E8"),
            "Крикли" => ("гоблинам", "быстрый практичный жаргон гоблинов.", "#A7C746"),
            "Шелар" => ("шелегам", "размеренная речь шелегов с долгими гласными.", "#B5B9DF"),
            "Арканийский" => ("арканам", "мелодичный язык аркан с ритуальными оборотами.", "#D888E8"),
            "НекоМетрический" => ("фелинидам", "для стороннего наблюдателя — непонятная мешанина ломаного японского, но для фелинидов эта речь естественна и понятна.", "#E5A1C7"), // Radiant Sector: adapted feline speech.
            _ => ("носителям", "родной язык вашего вида.", "#F2F6FB")
        };

        // Radiant Sector: explicit line breaks keep longer language descriptions readable.
        Title = nativeLanguage;
        InfoText.SetMarkup($"[bold][color={color}]{nativeLanguage}[/color][/bold]\n[font size=12][color={color}]Доступен {species}.\n{description}\n\nЕго полностью понимают только носители этого языка;\nдля остальных речь выглядит искажённой.[/color][/font]");
